// 'both' mode: every label shows Tamil first, then English (skipping duplicates like "Craft2Cart")
const BOTH = Object.fromEntries(
  Object.keys(TRANSLATIONS.en).map((key) => {
    const en = (TRANSLATIONS.en as Record<string, string>)[key];
    const ta = (TRANSLATIONS.ta as Record<string, string>)[key];
    return [key, en === ta ? en : `${ta} \u00b7 ${en}`];
  })
) as typeof TRANSLATIONS.en;

export const getTranslation = (lang: Language) =>
  lang === 'ta' ? TRANSLATIONS.ta : lang === 'both' ? BOTH : TRANSLATIONS.en;

// Helper for inline bilingual labels: Tamil only, English only, or "Tamil \u00b7 English"
export const bi = (ta: string, en: string, lang: Language) =>
  lang === 'ta' ? ta : lang === 'en' ? en : `${ta} \u00b7 ${en}`;

// Speech helper: Tamil voice text for 'ta' and 'both', English for 'en'
export const speechFor = (lang: Language, en: string, ta: string) =>
  lang === 'en' ? en : ta;
